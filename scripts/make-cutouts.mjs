/**
 * Cuts product packshots out of their white studio background so they can
 * stand on shelves and fly into the basket.
 *
 *   node scripts/make-cutouts.mjs
 *
 * Reads public/media/products/<slug>/01.jpg and writes
 * public/media/cutouts/<slug>.webp (transparent, trimmed, max 900px tall).
 * The background is found by flood-filling near-white pixels from the image
 * edges, so white inside labels is kept. Products photographed on a coloured
 * background are skipped and listed at the end. Also writes
 * src/lib/cutouts.ts, the list the site uses to know which cut-outs exist.
 */
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const SOURCE_ROOT = "public/media/products";
const OUTPUT_ROOT = "public/media/cutouts";
const WORK_HEIGHT = 1100;
const MAX_HEIGHT = 900;

fs.mkdirSync(OUTPUT_ROOT, { recursive: true });

function isBackground(r, g, b) {
  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  return min > 228 && max - min < 18;
}

async function cutout(slug) {
  const input = path.join(SOURCE_ROOT, slug, "01.jpg");
  const { data, info } = await sharp(input)
    .resize({ height: WORK_HEIGHT, withoutEnlargement: true })
    .removeAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  const { width: w, height: h } = info;

  // Corners must be studio white, otherwise this isn't a cut-out candidate.
  const corner = (x, y) => {
    const i = (y * w + x) * 3;
    return isBackground(data[i], data[i + 1], data[i + 2]);
  };
  if (![corner(2, 2), corner(w - 3, 2), corner(2, h - 3), corner(w - 3, h - 3)].every(Boolean)) {
    return "skipped";
  }

  // Flood fill from every edge pixel.
  const bg = new Uint8Array(w * h);
  const stack = [];
  const push = (x, y) => {
    const p = y * w + x;
    if (bg[p]) return;
    const i = p * 3;
    if (!isBackground(data[i], data[i + 1], data[i + 2])) return;
    bg[p] = 1;
    stack.push(p);
  };
  for (let x = 0; x < w; x++) {
    push(x, 0);
    push(x, h - 1);
  }
  for (let y = 0; y < h; y++) {
    push(0, y);
    push(w - 1, y);
  }
  while (stack.length) {
    const p = stack.pop();
    const x = p % w;
    const y = (p - x) / w;
    if (x > 0) push(x - 1, y);
    if (x < w - 1) push(x + 1, y);
    if (y > 0) push(x, y - 1);
    if (y < h - 1) push(x, y + 1);
  }

  // Alpha: background 0, product 255, with a soft 1px fringe that fades
  // light edge pixels so no white halo remains.
  const rgba = Buffer.alloc(w * h * 4);
  for (let p = 0; p < w * h; p++) {
    const i = p * 3;
    const o = p * 4;
    rgba[o] = data[i];
    rgba[o + 1] = data[i + 1];
    rgba[o + 2] = data[i + 2];
    if (bg[p]) {
      rgba[o + 3] = 0;
      continue;
    }
    const x = p % w;
    const y = (p - x) / w;
    const nearBg =
      (x > 0 && bg[p - 1]) || (x < w - 1 && bg[p + 1]) || (y > 0 && bg[p - w]) || (y < h - 1 && bg[p + w]);
    if (nearBg) {
      const lightness = (data[i] + data[i + 1] + data[i + 2]) / 3;
      rgba[o + 3] = lightness > 200 ? Math.round(255 * (1 - (lightness - 200) / 70)) : 220;
    } else {
      rgba[o + 3] = 255;
    }
  }

  await sharp(rgba, { raw: { width: w, height: h, channels: 4 } })
    .blur(0.3)
    .trim({ threshold: 1 })
    .resize({ height: MAX_HEIGHT, withoutEnlargement: true })
    .webp({ quality: 86, alphaQuality: 90 })
    .toFile(path.join(OUTPUT_ROOT, `${slug}.webp`));
  return "ok";
}

const skipped = [];
const made = [];
for (const slug of fs.readdirSync(SOURCE_ROOT).sort()) {
  if (!fs.existsSync(path.join(SOURCE_ROOT, slug, "01.jpg"))) continue;
  const result = await cutout(slug);
  if (result === "skipped") skipped.push(slug);
  else made.push(slug);
  console.log(`${result.padEnd(7)} ${slug}`);
}
if (skipped.length) console.log(`\nNot cut out (coloured background): ${skipped.join(", ")}`);

fs.writeFileSync(
  "src/lib/cutouts.ts",
  `// Generated by scripts/make-cutouts.mjs — do not edit by hand.

/** Products with a transparent cut-out in public/media/cutouts. */
export const CUTOUT_SLUGS = new Set<string>(${JSON.stringify(made, null, 2)});

/** Transparent cut-out of a product, or null if it was shot on a coloured ground. */
export function cutoutFor(slug: string): string | null {
  return CUTOUT_SLUGS.has(slug) ? \`/media/cutouts/\${slug}.webp\` : null;
}
`,
);
